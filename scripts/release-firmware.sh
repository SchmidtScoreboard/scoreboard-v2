#!/usr/bin/env bash
# Build + sign an OTA firmware release into firmware-dist/.
#
#   1. version <- firmware-rs/Cargo.toml [package].version (CalVer "YYYY.M.P")
#   2. pubkey  <- sign-firmware --print-pubkey (generates the signing key at
#                 ~/.config/scoreboard/firmware-signing.key on first use), then
#                 firmware-rs/src/fw_pubkey.rs is (re)written to match — the
#                 firmware build below always bakes in the current key, and a
#                 changed key naturally triggers a rebuild (it's a source file)
#   3. build   <- cargo build --release in firmware-rs (xtensa toolchain via
#                 ~/export-esp.sh). Builds with --features prod by default so
#                 the shipped image talks to the prod server; override with
#                 FEATURES="" (dev) or FEATURES="foo,bar".
#   4. image   <- espflash save-image --chip esp32s3 (ELF -> raw app image),
#                 size-checked against the 3MB ota_0 slot in partitions.csv
#   5. sign    <- sign-firmware writes firmware-dist/firmware.json
#                 { version, size, sha256, sig }
#
# Commit firmware-dist/ afterwards: the Dockerfile ships it inside the server
# image (FIRMWARE_DIR=/firmware-dist), which serves GET /firmware/latest and
# GET /firmware.bin to boards.
set -euo pipefail
cd "$(dirname "$0")/.."

FEATURES="${FEATURES-prod}"

# First `version = "..."` line is [package].version (dependency tables are inline).
VERSION="$(sed -n 's/^version *= *"\(.*\)"/\1/p' firmware-rs/Cargo.toml | head -1)"
if [[ -z "$VERSION" ]]; then
    echo "error: could not read package.version from firmware-rs/Cargo.toml" >&2
    exit 1
fi

echo "==> release version $VERSION (from firmware-rs/Cargo.toml)"

echo "==> signing key / public key"
PUBKEY="$(cargo run -q -p server --bin sign-firmware -- --print-pubkey)"
if [[ ! "$PUBKEY" =~ ^[0-9a-f]{64}$ ]]; then
    echo "error: sign-firmware --print-pubkey returned '$PUBKEY' (expected 64 hex chars)" >&2
    exit 1
fi

# Bake the pubkey into the firmware source. Only rewrite on change, so
# unchanged keys don't dirty the build.
PUBKEY_RS=firmware-rs/src/fw_pubkey.rs
GENERATED="$(cat <<EOF
//! GENERATED by scripts/release-firmware.sh — do not edit by hand.
//!
//! Ed25519 public key (hex) matching ~/.config/scoreboard/firmware-signing.key.
//! The board installs an OTA image only if its signature verifies against this
//! key.
pub const FW_PUBKEY_HEX: &str = "$PUBKEY";
EOF
)"
if [[ "$(cat "$PUBKEY_RS" 2>/dev/null)" != "$GENERATED" ]]; then
    printf '%s\n' "$GENERATED" > "$PUBKEY_RS"
    echo "==> wrote $PUBKEY_RS (pubkey $PUBKEY)"
else
    echo "==> $PUBKEY_RS already matches (pubkey $PUBKEY)"
fi

echo "==> building firmware (features: ${FEATURES:-<none>})"
# Subshell: export-esp.sh mutates PATH/env for the xtensa toolchain, and the
# host cargo invocation below must not inherit that.
(
    cd firmware-rs
    # xtensa-esp32s3-elf-gcc must be on PATH for the link step.
    [[ -f "$HOME/export-esp.sh" ]] && source "$HOME/export-esp.sh"
    cargo build --release ${FEATURES:+--features "$FEATURES"}
)

echo "==> converting ELF to app image"
mkdir -p firmware-dist
# --partition-table/--target-app-partition make espflash verify the image fits
# the 3MB ota_0 slot (and never pad: non-merge save-image emits the app only).
# --flash-size 8mb: the MatrixPortal S3's flash — with no chip attached to
# probe, espflash assumes 4MB and rejects our 6.4MB partition layout.
espflash save-image --chip esp32s3 \
    --flash-size 8mb \
    --partition-table firmware-rs/partitions.csv \
    --target-app-partition ota_0 \
    firmware-rs/target/xtensa-esp32s3-none-elf/release/firmware-rs \
    firmware-dist/firmware.bin

echo "==> signing"
cargo run -q -p server --bin sign-firmware -- firmware-dist/firmware.bin "$VERSION"

echo
echo "=============================================================="
echo "  Release $VERSION ready in firmware-dist/"
echo "  - firmware.bin  ($(wc -c < firmware-dist/firmware.bin | tr -d ' ') bytes)"
echo "  - firmware.json (version/size/sha256/sig)"
echo "  Commit firmware-dist/ (and $PUBKEY_RS if it changed), then deploy"
echo "  the server — boards see the update on their next BoardState."
echo "=============================================================="
