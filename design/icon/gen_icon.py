#!/usr/bin/env python3
"""Generate the Scoreboard app icon: board SVG (+ layers) for Icon Composer,
and Android adaptive-icon vector drawables. One geometry, every output."""
import os, sys
ROOT = sys.argv[1]
S = 1024
COLS, ROWS = 40, 20
PW = S * 0.70; PH = PW / 2; BEZ = 26
DIAL_W = PW * 0.05; DIAL_H = PH * 0.40
TOTAL_W = PW + 2 * BEZ + DIAL_W
PX = (S - TOTAL_W) / 2 + DIAL_W; PY = (S - PH) / 2
DIAL_Y = PY - BEZ + (PH + 2 * BEZ) * 0.33 - DIAL_H / 2
PITCH = PW / COLS; GAP = PITCH * 0.14; DOT = PITCH - GAP; DOT_RX = DOT * 0.18

FACE = '#0B0B0E'; UNLIT = '#1F2024'; DIAL = '#2A2B30'; WHITE = '#F4F4F6'
STL, STL2 = '#002F87', '#FCB514'      # ESPN colour / alternate, kept by ensure_contrast
CHI, CHI2 = '#CF0A2C', '#000000'

D = {
 '2':['111','001','111','100','111'],'4':['101','101','111','001','001'],
 'A':['010','101','111','101','101'],'C':['111','100','100','100','111'],
 'F':['111','100','110','100','100'],'H':['101','101','111','101','101'],
 'I':['111','010','010','010','111'],'L':['100','100','100','100','111'],
 'N':['101','111','111','101','101'],'S':['111','100','111','001','111'],
 'T':['111','010','010','010','010'],
}
cells = {}
def block(x0,y0,x1,y1,c):
    for y in range(y0,y1+1):
        for x in range(x0,x1+1): cells[(x,y)] = c
def text(s,ox,oy,c):
    x = ox
    for ch in s:
        for yy,row in enumerate(D[ch]):
            for xx,b in enumerate(row):
                if b == '1': cells[(x+xx,oy+yy)] = c
        x += 4
# The server's game frame at half resolution: two full-width bands from the
# top edge, accent stripe at the left, name beside it, score right-aligned,
# black status strip below. Blues (away) 2, Blackhawks (home) 4, FINAL.
block(0,0,39,6,STL); block(0,7,39,13,CHI)
block(0,0,0,6,STL2); block(0,7,0,13,CHI2)
text('STL',3,1,STL2); text('2',36,1,STL2)
text('CHI',3,8,CHI2); text('4',36,8,CHI2)
text('FINAL',11,15,WHITE)

def f(v): return f'{v:.2f}'.rstrip('0').rstrip('.')
def rrect_path(x,y,w,h,r):
    r = min(r, w/2, h/2)
    return (f'M{f(x+r)} {f(y)}H{f(x+w-r)}A{f(r)} {f(r)} 0 0 1 {f(x+w)} {f(y+r)}'
            f'V{f(y+h-r)}A{f(r)} {f(r)} 0 0 1 {f(x+w-r)} {f(y+h)}H{f(x+r)}'
            f'A{f(r)} {f(r)} 0 0 1 {f(x)} {f(y+h-r)}V{f(y+r)}A{f(r)} {f(r)} 0 0 1 {f(x+r)} {f(y)}Z')

# ---- geometry as (name, colour, pathdata) shapes, grouped by layer ----
dial = [('dial', DIAL, rrect_path(PX-BEZ-DIAL_W, DIAL_Y, DIAL_W+BEZ, DIAL_H, DIAL_W*0.45))]
face = [('face', FACE, rrect_path(PX-BEZ, PY-BEZ, PW+2*BEZ, PH+2*BEZ, 30))]
by_colour = {}
for y in range(ROWS):
    for x in range(COLS):
        c = cells.get((x,y), UNLIT)
        by_colour.setdefault(c, []).append(rrect_path(PX+x*PITCH+GAP/2, PY+y*PITCH+GAP/2, DOT, DOT, DOT_RX))
order = [UNLIT, STL, CHI, STL2, CHI2, WHITE]
leds = [('leds-'+c.strip('#'), c, ''.join(by_colour[c])) for c in order if c in by_colour]

def svg(shapes, bg=None):
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{S}" height="{S}" viewBox="0 0 {S} {S}">']
    if bg: out.append(bg)
    for name,colour,d in shapes:
        out.append(f'  <path id="{name}" fill="{colour}" d="{d}"/>')
    out.append('</svg>\n')
    return '\n'.join(out)

def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path,'w') as fh: fh.write(content)
    print('wrote', os.path.relpath(path, ROOT))

icon_dir = os.path.join(ROOT, 'design', 'icon')
write(os.path.join(icon_dir, 'board.svg'), svg(dial+face+leds))
write(os.path.join(icon_dir, 'layers', '01-dial.svg'), svg(dial))
write(os.path.join(icon_dir, 'layers', '02-face.svg'), svg(face))
write(os.path.join(icon_dir, 'layers', '03-leds.svg'), svg(leds))

# Android preview: the light blue gradient the background drawable uses.
GRAD_A, GRAD_B = '#D6EDFF', '#86C1F1'
grad = (f'<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{GRAD_A}"/><stop offset="1" stop-color="{GRAD_B}"/></linearGradient></defs>'
        f'<rect width="{S}" height="{S}" fill="url(#g)"/>')
write(os.path.join(icon_dir, 'android-preview.svg'), svg(dial+face+leds, bg=grad))

# ---- Android adaptive icon ----
# 108dp canvas; the launcher shows the inner 72dp. The 1024 canvas maps to
# that 72dp so the board sits where the previews showed it.
res = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'res')
scale = 72 / S
fg = ['<?xml version="1.0" encoding="utf-8"?>',
      '<!-- Generated by design/icon/gen_icon.py — edit the script, not this file. -->',
      '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
      '    android:width="108dp" android:height="108dp"',
      '    android:viewportWidth="108" android:viewportHeight="108">',
      f'  <group android:translateX="18" android:translateY="18" android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">']
for name,colour,d in dial+face+leds:
    fg.append(f'    <path android:name="{name}" android:fillColor="{colour}" android:pathData="{d}"/>')
fg += ['  </group>', '</vector>', '']
write(os.path.join(res, 'drawable', 'ic_launcher_foreground.xml'), '\n'.join(fg))

bg = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/icon/gen_icon.py — edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
  <path android:pathData="M0 0H108V108H0Z">
    <aapt:attr name="android:fillColor">
      <gradient android:type="linear"
          android:startX="0" android:startY="0" android:endX="108" android:endY="108"
          android:startColor="{GRAD_A}" android:endColor="{GRAD_B}"/>
    </aapt:attr>
  </path>
</vector>
'''
write(os.path.join(res, 'drawable', 'ic_launcher_background.xml'), bg)
adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
'''
write(os.path.join(res, 'mipmap-anydpi-v26', 'ic_launcher.xml'), adaptive)
write(os.path.join(res, 'mipmap-anydpi-v26', 'ic_launcher_round.xml'), adaptive)
